export interface Stroke {
  smooth: boolean;
  pts: [number, number][];
}

export interface Glyph {
  w: number;
  strokes: Stroke[];
}

/** A skeleton in the `"width; stroke | stroke"` form above (the doodles in the margins use it too). */
export function parse(s: string): Glyph {
  const [w, rest] = s.split(';');
  const strokes = rest.split('|').map((part) => {
    const t = part.trim();
    const smooth = t.startsWith('~');
    const pts = t
      .replace('~', '')
      .split(/\s+/)
      .filter(Boolean)
      .map((p) => p.split(',').map(Number) as [number, number]);
    return { smooth, pts };
  });
  return { w: Number(w), strokes };
}

/** A whole hand's skeletons (`SOURCE` above, or another writer's), every variant parsed once. */
export const parseSet = (source: Record<string, string[]>): Record<string, Glyph[]> => Object.fromEntries(Object.entries(source).map(([k, v]) => [k, v.map(parse)]));

